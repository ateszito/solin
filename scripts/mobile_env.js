#!/usr/bin/env node
/* ============================================================
   Solin — scripts/mobile_env.js
   Configures the mobile build environment for Capacitor iOS/Android.
   Supports: dev | staging | prod
   Usage: node scripts/mobile_env.js <dev|staging|prod>
   ============================================================ */

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const APP_DIR = path.join(ROOT, "app");
const IOS_DIR = path.join(ROOT, "ios");

const TARGETS = {
  dev: {
    key: "dev",
    env: "development",
    appId: "com.ateszito.solin.dev",
    appName: "Solin (Dev)",
    apiBase: "https://solin-dev.ateszito.com",
    envFile: ".env.development",
    debug: "true"
  },
  staging: {
    key: "staging",
    env: "staging",
    appId: "com.ateszito.solin.staging",
    appName: "Solin (Stg)",
    apiBase: "https://solin-staging.ateszito.com",
    envFile: ".env.staging",
    debug: "false"
  },
  prod: {
    key: "prod",
    env: "production",
    appId: "com.ateszito.solin",
    appName: "Solin",
    apiBase: "https://solin.ateszito.com",
    envFile: ".env.production",
    debug: "false"
  }
};

const rawTarget = (process.argv[2] || "").toLowerCase().trim();
const normalizedTarget =
  rawTarget === "development" ? "dev" :
  rawTarget === "production" ? "prod" : rawTarget;

if (!TARGETS[normalizedTarget]) {
  console.error("Usage: node scripts/mobile_env.js <dev|staging|prod>");
  process.exit(1);
}

const target = TARGETS[normalizedTarget];
console.log(`[mobile_env] Configuring mobile environment: ${target.appName} (${target.appId})`);

// 1. Read version from VERSION file or .env file
let version = "0.1.3";
try {
  const versionFile = path.join(ROOT, "VERSION");
  if (fs.existsSync(versionFile)) {
    version = fs.readFileSync(versionFile, "utf8").trim();
  }
} catch (e) {}

const appVersion = `v${version}-${target.key}`;

// 2. Write app/_solin.env.js
const solinEnvContent = `/* Auto-generated by scripts/mobile_env.js for ${target.appName} */
window.SOLIN_CONFIG = {
  SOLIN_ENV: "${target.env}",
  APP_VERSION: "${appVersion}",
  API_BASE_URL: "${target.apiBase}",
  PUBLIC_BASE_URL: "${target.apiBase}",
  FEATURE_ALLOW_EDIT: "true",
  FEATURE_INVISIBILITY: "true",
  DEBUG: "${target.debug}"
};
`;

fs.writeFileSync(path.join(APP_DIR, "_solin.env.js"), solinEnvContent, "utf8");
console.log(`[mobile_env] Wrote app/_solin.env.js (API_BASE_URL=${target.apiBase})`);

// 3. Update capacitor.config.json
const capConfigPath = path.join(ROOT, "capacitor.config.json");
const capConfig = {
  appId: target.appId,
  appName: target.appName,
  webDir: "app",
  server: {
    androidScheme: "https",
    iosScheme: "capacitor"
  },
  plugins: {
    StatusBar: {
      style: "DARK"
    }
  }
};

fs.writeFileSync(capConfigPath, JSON.stringify(capConfig, null, 2) + "\n", "utf8");
console.log(`[mobile_env] Updated capacitor.config.json (appId=${target.appId}, appName="${target.appName}")`);

// 4. Update iOS Info.plist (CFBundleDisplayName & Permissions)
const infoPlistPath = path.join(IOS_DIR, "App", "App", "Info.plist");
if (fs.existsSync(infoPlistPath)) {
  let plist = fs.readFileSync(infoPlistPath, "utf8");
  plist = plist.replace(
    /(<key>CFBundleDisplayName<\/key>\s*<string>)(.*?)(<\/string>)/,
    `$1${target.appName}$3`
  );
  if (!plist.includes("NSCameraUsageDescription")) {
    const permString = `\t<key>NSCameraUsageDescription</key>\n\t<string>A Solin hozzáférést kér a kamerához a termékfotók készítéséhez és a tápérték címkék beolvasásához.</string>\n\t<key>NSPhotoLibraryUsageDescription</key>\n\t<string>A Solin hozzáférést kér a fotótárhoz a termékfotók és címkék kiválasztásához.</string>\n\t<key>NSPhotoLibraryAddUsageDescription</key>\n\t<string>A Solin hozzáférést kér a fotók mentéséhez.</string>\n</dict>`;
    plist = plist.replace("</dict>", permString);
  }
  fs.writeFileSync(infoPlistPath, plist, "utf8");
  console.log(`[mobile_env] Updated iOS Info.plist CFBundleDisplayName -> "${target.appName}" and ensured Camera/Photo permissions`);
}

// 5. Update iOS project.pbxproj (PRODUCT_BUNDLE_IDENTIFIER)
const pbxPath = path.join(IOS_DIR, "App", "App.xcodeproj", "project.pbxproj");
if (fs.existsSync(pbxPath)) {
  let pbx = fs.readFileSync(pbxPath, "utf8");
  pbx = pbx.replace(
    /PRODUCT_BUNDLE_IDENTIFIER = com\.ateszito\.solin.*?;/g,
    `PRODUCT_BUNDLE_IDENTIFIER = ${target.appId};`
  );
  fs.writeFileSync(pbxPath, pbx, "utf8");
  console.log(`[mobile_env] Updated iOS project.pbxproj PRODUCT_BUNDLE_IDENTIFIER -> ${target.appId}`);
}

// 6. Run Capacitor Sync
console.log("[mobile_env] Running cap sync ios...");
execSync("npx cap sync ios", { cwd: ROOT, stdio: "inherit" });

// 7. Fix symlinks in ios/App/App/public (Apple installd strictly forbids escaping/broken symlinks)
function fixSymlinks() {
  const publicDir = path.join(IOS_DIR, "App", "App", "public");
  if (!fs.existsSync(publicDir)) return;

  const entries = fs.readdirSync(publicDir);
  for (const entry of entries) {
    const fullPath = path.join(publicDir, entry);
    try {
      const stat = fs.lstatSync(fullPath);
      if (stat.isSymbolicLink()) {
        const srcPath = path.join(APP_DIR, entry);
        fs.unlinkSync(fullPath);
        if (fs.existsSync(srcPath)) {
          fs.cpSync(srcPath, fullPath, { recursive: true, dereference: true });
          console.log(`[mobile_env] Replaced symlink with real directory: ${entry}`);
        }
      }
    } catch (e) {
      console.warn(`[mobile_env] Warning fixing symlink ${entry}:`, e.message);
    }
  }

  // Also clean stale build caches from Xcode DerivedData
  try {
    const derivedDataDir = path.join(process.env.HOME || "", "Library/Developer/Xcode/DerivedData");
    if (fs.existsSync(derivedDataDir)) {
      const items = fs.readdirSync(derivedDataDir).filter(n => n.startsWith("App-"));
      for (const item of items) {
        const buildDir = path.join(derivedDataDir, item, "Build/Products");
        if (fs.existsSync(buildDir)) {
          execSync(`find "${buildDir}" -name "VideoContent" -type l -exec rm -rf {} + 2>/dev/null || true`);
        }
      }
    }
  } catch (e) {}
}

fixSymlinks();

console.log(`[mobile_env] Ready! Switch to Xcode and hit Run (Cmd + R) to install ${target.appName} on your phone.`);
